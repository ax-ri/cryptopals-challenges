pub fn detect_aes_ecb(bytes: &[u8]) -> bool {
    assert_eq!(bytes.len() % 16, 0);

    let mut count: u32 = 0;
    let (blocks, _) = bytes.as_chunks::<16>();
    for (i, b) in blocks.iter().enumerate() {
        for (j, b2) in blocks.iter().enumerate() {
            if i != j && b == b2 {
                count += 1;
            }
        }
    }
    count > 0
}

