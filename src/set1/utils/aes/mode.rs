    pub fn encrypt(bytes: &[u8], key: &Key) -> Vec<u8> {
        if bytes.is_empty() {
            return vec![];
        }

        let keys = core::expand_key(key);

        let (blocks, last) = bytes.as_chunks::<16>();
        // pad the last block with PKCS7-padding
        let last: [u8; 16] = {
            let mut last = last.to_vec();
            let padding_count = 16 - (bytes.len() % 16);
            let mut padding = vec![padding_count as u8; padding_count];
            last.append(&mut padding);
            debug_assert!(last.len() == 16);
            last.try_into().unwrap() // conversion will always be successful as last is 16-byte long
        };

        // encrypt each block in parallel
        let mut encryted = blocks
            .into_par_iter()
            .map(|b| core::encrypt_state(b, &keys))
            .collect::<Vec<_>>();
        encryted.push(core::encrypt_state(&last, &keys));

        // flatten the blocks
        encryted.concat()
    }

    pub fn decrypt(bytes: &[u8], key: &Key) -> Result<Vec<u8>, DecryptError> {
        if bytes.is_empty() {
            return Ok(vec![]);
        }

        let keys = core::expand_key(key);

        let (blocks, last) = bytes.as_chunks::<16>();
        if !last.is_empty() {
            return Err(DecryptError::InvalidInput);
        }
        let (last, blocks) = blocks.split_last().unwrap();

        // decrypt each block in parallel
        let mut decrypted = blocks
            .into_par_iter()
            .map(|b| core::decrypt_state(b, &keys))
            .collect::<Vec<_>>()
            .concat();

        // add the last decrypted block, with padding removed
        let last_decrypted = core::decrypt_state(last, &keys);
        let padding_count = *last_decrypted.last().unwrap();
        decrypted.extend(&last_decrypted[..(16 - padding_count as usize)]);

        Ok(decrypted)
    }

