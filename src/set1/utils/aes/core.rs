type Word = [u8; 4];
pub(crate) type Key = [u8; 16];
type ExpandedKey = [Key; 11];
type State = [u8; 16];

////////////////////////////////////////////////////////////////////////////////////////////////////

fn rot_word(w: &Word) -> Word {
    let mut w = *w;
    w.rotate_left(1);
    w
}

fn sub_word(w: &Word, s_box: &[u8; 256]) -> Word {
    let converter = |b: &u8| s_box[(((b & 0xF0) >> 4) * 16 + (b & 0x0F)) as usize];
    let mut w = *w;
    for b in w.as_mut() {
        *b = converter(b);
    }
    w
}

fn rcon(i: usize) -> Word {
    [RCON[i], 0, 0, 0]
}

fn xor_words(a: &Word, b: &Word) -> Word {
    [a[0] ^ b[0], a[1] ^ b[1], a[2] ^ b[2], a[3] ^ b[3]]
}

////////////////////////////////////////////////////////////////////////////////////////////////////

pub(crate) fn expand_key(key: &Key) -> ExpandedKey {
    let mut keys: ExpandedKey = [[0; 16]; 11];

    keys[0] = *key;

    for round_idx in 1..11 {
        let previous_block = keys[round_idx - 1];

        let w = sub_word(&rot_word(previous_block[12..].try_into().unwrap()), &S_BOX);
        let w = xor_words(&w, previous_block[..4].try_into().unwrap());
        let w = xor_words(&w, &rcon(round_idx));

        keys[round_idx][..4].copy_from_slice(&w);

        let mut w = w;
        for idx in 1..4 {
            let range = (idx * 4)..((idx + 1) * 4);
            keys[round_idx][range.clone()].copy_from_slice(&xor_words(
                previous_block[range.clone()].try_into().unwrap(),
                &w,
            ));
            w = keys[round_idx][range].try_into().unwrap();
        }
    }
    keys
}

