fn print_state(s: &State) {
    for i in 0..4 {
        for j in 0..4 {
            print!("{:02x} ", s[j * 4 + i]);
        }
        println!();
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////

fn sub_bytes_base(s: &State, s_box: &[u8; 256]) -> State {
    let mut out = [0; 16];

    out[..4].copy_from_slice(&sub_word(&s[..4].try_into().unwrap(), s_box));
    out[4..8].copy_from_slice(&sub_word(&s[4..8].try_into().unwrap(), s_box));
    out[8..12].copy_from_slice(&sub_word(&s[8..12].try_into().unwrap(), s_box));
    out[12..].copy_from_slice(&sub_word(&s[12..].try_into().unwrap(), s_box));

    out
}

fn mix_columns_base<F>(s: &State, mixer: F) -> State
where
    F: Fn(&[u8; 4]) -> [u8; 4],
{
    let mut s2: State = [0; 16];

    s2[..4].copy_from_slice(&mixer(s[..4].try_into().unwrap()));
    s2[4..8].copy_from_slice(&mixer(s[4..8].try_into().unwrap()));
    s2[8..12].copy_from_slice(&mixer(s[8..12].try_into().unwrap()));
    s2[12..].copy_from_slice(&mixer(s[12..].try_into().unwrap()));

    s2
}

////////////////////////////////////////////////////////////////////////////////////////////////////

fn sub_bytes(s: &State) -> State {
    sub_bytes_base(s, &S_BOX)
}

fn shift_rows(s: &State) -> State {
    let mut s2: State = [0; 16];

    s2[0] = s[0];
    s2[1] = s[5];
    s2[2] = s[10];
    s2[3] = s[15];

    s2[4] = s[4];
    s2[5] = s[9];
    s2[6] = s[14];
    s2[7] = s[3];

    s2[8] = s[8];
    s2[9] = s[13];
    s2[10] = s[2];
    s2[11] = s[7];

    s2[12] = s[12];
    s2[13] = s[1];
    s2[14] = s[6];
    s2[15] = s[11];

    s2
}

fn mix_columns(s: &State) -> State {
    mix_columns_base(s, |b: &[u8; 4]| {
        [
            MUL_BY_2[b[0] as usize] ^ MUL_BY_3[b[1] as usize] ^ b[2] ^ b[3],
            b[0] ^ MUL_BY_2[b[1] as usize] ^ MUL_BY_3[b[2] as usize] ^ b[3],
            b[0] ^ b[1] ^ MUL_BY_2[b[2] as usize] ^ MUL_BY_3[b[3] as usize],
            MUL_BY_3[b[0] as usize] ^ b[1] ^ b[2] ^ MUL_BY_2[b[3] as usize],
        ]
    })
}

fn sub_bytes_inverse(s: &State) -> State {
    sub_bytes_base(s, &S_BOX_INVERSE)
}

fn shift_rows_inverse(s: &State) -> State {
    let mut s2: State = [0; 16];

    s2[0] = s[0];
    s2[1] = s[13];
    s2[2] = s[10];
    s2[3] = s[7];

    s2[4] = s[4];
    s2[5] = s[1];
    s2[6] = s[14];
    s2[7] = s[11];

    s2[8] = s[8];
    s2[9] = s[5];
    s2[10] = s[2];
    s2[11] = s[15];

    s2[12] = s[12];
    s2[13] = s[9];
    s2[14] = s[6];
    s2[15] = s[3];

    s2
}

fn mix_columns_inverse(s: &State) -> State {
    mix_columns_base(s, |b: &[u8; 4]| {
        [
            MUL_BY_14[b[0] as usize]
                ^ MUL_BY_11[b[1] as usize]
                ^ MUL_BY_13[b[2] as usize]
                ^ MUL_BY_9[b[3] as usize],
            MUL_BY_9[b[0] as usize]
                ^ MUL_BY_14[b[1] as usize]
                ^ MUL_BY_11[b[2] as usize]
                ^ MUL_BY_13[b[3] as usize],
            MUL_BY_13[b[0] as usize]
                ^ MUL_BY_9[b[1] as usize]
                ^ MUL_BY_14[b[2] as usize]
                ^ MUL_BY_11[b[3] as usize],
            MUL_BY_11[b[0] as usize]
                ^ MUL_BY_13[b[1] as usize]
                ^ MUL_BY_9[b[2] as usize]
                ^ MUL_BY_14[b[3] as usize],
        ]
    })
}

fn add_round_key(s: &State, round_idx: usize, keys: &ExpandedKey) -> State {
    let k = keys[round_idx];
    [
        s[0] ^ k[0],
        s[1] ^ k[1],
        s[2] ^ k[2],
        s[3] ^ k[3],
        s[4] ^ k[4],
        s[5] ^ k[5],
        s[6] ^ k[6],
        s[7] ^ k[7],
        s[8] ^ k[8],
        s[9] ^ k[9],
        s[10] ^ k[10],
        s[11] ^ k[11],
        s[12] ^ k[12],
        s[13] ^ k[13],
        s[14] ^ k[14],
        s[15] ^ k[15],
    ]
}

////////////////////////////////////////////////////////////////////////////////////////////////////

pub(crate) fn encrypt_state(s: &State, keys: &ExpandedKey) -> State {
    let mut s = add_round_key(s, 0, keys);
    for round_idx in 1..10 {
        s = mix_columns(&shift_rows(&sub_bytes(&s)));
        s = add_round_key(&s, round_idx, keys);
    }
    s = shift_rows(&sub_bytes(&s));
    s = add_round_key(&s, 10, keys);
    s
}

pub(crate) fn decrypt_state(s: &State, keys: &ExpandedKey) -> State {
    let mut s = add_round_key(s, 10, keys);
    s = sub_bytes_inverse(&shift_rows_inverse(&s));

    for round_idx in (1..10).rev() {
        s = add_round_key(&s, round_idx, keys);
        s = sub_bytes_inverse(&shift_rows_inverse(&mix_columns_inverse(&s)));
    }
    s = add_round_key(&s, 0, keys);
    s
}

